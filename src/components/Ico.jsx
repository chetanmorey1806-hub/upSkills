const EMOJI = /[\u{1F000}-\u{1FAFF}\u2600-\u27BF\u2B00-\u2BFF\u23E9-\u23FA\u231A\u231B\u2139]/u;
export const norm = (e) => String(e ?? '').replace(/\uFE0F/g, '').trim();
export const iconFor = (e) => MAP[norm(e)]?.[0];

export default function Ico({ e, size = '1.05em', className = '', fallback = CircleDot, ...rest }) {
  if (e == null || e === '' || e === false) return null;
  if (typeof e !== 'string') {
    if (isValidElement(e)) return e;
    const C = e;
    return <C size={size} strokeWidth={2} className={`ico ${className}`} aria-hidden="true" {...rest} />;
  }
  const hit = MAP[norm(e)];
  if (!hit && !EMOJI.test(e.replace(/[✓✔✗✕✖✘★☆➜✎]/g, ''))) return <span className={`ico-txt ${className}`}>{e}</span>;
  const I = hit ? hit[0] : fallback;
  return <I size={size} strokeWidth={2} className={`ico${hit && hit[1] ? ` t-${hit[1]}` : ''} ${className}`} aria-hidden="true" {...rest} />;
}
