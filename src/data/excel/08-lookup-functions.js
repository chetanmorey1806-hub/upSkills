      content: `\`VLOOKUP\` searches for a value in the **first column** of a table and returns a value from a column to the right, identified by its number.\n\nThe last argument decides the match type. \`FALSE\` (or 0) means **exact match** - this is what you want 95% of the time (IDs, codes, names). \`TRUE\` (or 1, or omitted) means **approximate match**: the first column must be sorted ascending, and Excel returns the row with the largest value that is less than or equal to the lookup value. Approximate match is used for slabs: grades, tax brackets, commission tiers.`,
